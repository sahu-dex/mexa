#!/usr/bin/env python3
"""Generate a minimal composer-compatible autoloader in vendor/ from composer.lock.

Emits:
  vendor/composer/autoload_psr4.php
  vendor/composer/autoload_files.php
  vendor/composer/autoload_classmap.php
  vendor/autoload.php

Covers PSR-4, "files" includes and classmaps — everything this app's locked
packages use. Run install-vendor.py first. The app's own App\\, Database\\*
psr-4 mappings from composer.json are included via $baseDir.

NB: composer files occasionally carry double-escaped namespace keys, so keys
are normalized defensively (no-op on well-formed data).
"""
import json
import re
import glob
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
VENDOR = REPO / 'vendor'
COMP = VENDOR / 'composer'
lock = json.loads((REPO / 'composer.lock').read_text())
packages = lock['packages']


def php_str(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def normalize_ns(ns: str) -> str:
    return ns.replace('\\\\', '\\')


def scan_classes(root: Path, exclude_globs):
    """Find class/interface/trait declarations in php files."""
    classes = {}
    files = [root] if root.is_file() else list(root.rglob('*.php'))
    excluded = set()
    for g in exclude_globs:
        excluded.update(glob.glob(str(root / g), recursive=True))
    for f in files:
        if str(f) in excluded:
            continue
        try:
            src = f.read_text(errors='replace')
        except Exception:
            continue
        m = re.search(r'^\s*(?:abstract\s+|final\s+)*(?:class|interface|trait)\s+([A-Za-z_][A-Za-z0-9_]*)', src, re.M)
        if m:
            classes[m.group(1)] = f
    return classes


psr4 = {}
files_list = []
classmap = {}

for p in packages:
    name = p['name']
    a = p.get('autoload') or {}
    for f in a.get('files', []):
        files_list.append(f"{name}/{f}")
    for ns, dirs in (a.get('psr-4') or {}).items():
        ns = normalize_ns(ns)
        if isinstance(dirs, str):
            dirs = [dirs]
        for d in dirs:
            psr4.setdefault(ns, []).append(f"{name}/{d.rstrip('/')}/")
    exclude = a.get('exclude-from-classmap', [])
    for cm in a.get('classmap', []):
        cm_path = VENDOR / name / cm
        if not cm_path.exists():
            continue
        for cls, path in scan_classes(cm_path, exclude).items():
            classmap[cls] = str(Path(path).relative_to(VENDOR))

# The app's own namespaces (App\, Database\Factories\, Database\Seeders\, Tests\)
app_json = json.loads((REPO / 'composer.json').read_text())
for section in ('autoload', 'autoload-dev'):
    for ns, dirs in ((app_json.get(section) or {}).get('psr-4') or {}).items():
        ns = normalize_ns(ns)
        if isinstance(dirs, str):
            dirs = [dirs]
        for d in dirs:
            psr4.setdefault(ns, []).append(f"APP:{d.rstrip('/')}/")

COMP.mkdir(exist_ok=True)

lines = ['<?php', '// generated by scripts/preview/regen-autoload.py',
         '$vendorDir = dirname(__DIR__);', '$baseDir = dirname($vendorDir);', 'return [']
for ns, dirs in psr4.items():
    dirs_php = ', '.join(
        ("$baseDir . " + php_str('/' + d[4:]) if d.startswith('APP:') else "$vendorDir . " + php_str('/' + d))
        for d in dirs)
    lines.append(f"    {php_str(ns)} => [{dirs_php}],")
lines.append('];')
(COMP / 'autoload_psr4.php').write_text('\n'.join(lines) + '\n')

lines = ['<?php', '$vendorDir = dirname(__DIR__);', 'return [']
for f in files_list:
    lines.append(f"    $vendorDir . {php_str('/' + f)},")
lines.append('];')
(COMP / 'autoload_files.php').write_text('\n'.join(lines) + '\n')

lines = ['<?php', '$vendorDir = dirname(__DIR__);', 'return [']
for cls, path in sorted(classmap.items()):
    lines.append(f"    {php_str(cls)} => $vendorDir . {php_str('/' + path)},")
lines.append('];')
(COMP / 'autoload_classmap.php').write_text('\n'.join(lines) + '\n')

autoload_php = r'''<?php
// Minimal composer-compatible autoloader for the sandbox preview.
// Generated by scripts/preview/regen-autoload.py — regenerate after composer.lock changes.

$psr4 = require __DIR__ . '/composer/autoload_psr4.php';
$classMap = require __DIR__ . '/composer/autoload_classmap.php';
$files = require __DIR__ . '/composer/autoload_files.php';

$loader = function ($class) use ($psr4, $classMap) {
    if (isset($classMap[$class])) {
        composerIncludeFile($classMap[$class]);
        return;
    }
    $prefix = $class;
    while (false !== $pos = strrpos($prefix, '\\')) {
        $prefix = substr($class, 0, $pos + 1);
        $relative = substr($class, $pos + 1);
        if (isset($psr4[$prefix])) {
            $rel = str_replace('\\', '/', $relative) . '.php';
            foreach ($psr4[$prefix] as $dir) {
                if (is_file($dir . $rel)) {
                    composerIncludeFile($dir . $rel);
                    return;
                }
            }
        }
        $prefix = rtrim($prefix, '\\');
    }
    if (isset($psr4[''])) {
        $rel = str_replace('\\', '/', $class) . '.php';
        foreach ($psr4[''] as $dir) {
            if (is_file($dir . $rel)) {
                composerIncludeFile($dir . $rel);
                return;
            }
        }
    }
};
spl_autoload_register($loader);

foreach ($files as $file) {
    if (is_file($file)) {
        composerIncludeFile($file);
    }
}

function composerIncludeFile($file)
{
    require_once $file;
}

return true;
'''
(VENDOR / 'autoload.php').write_text(autoload_php)
print(f"psr4 namespaces: {len(psr4)}, files: {len(files_list)}, classmap: {len(classmap)}")
